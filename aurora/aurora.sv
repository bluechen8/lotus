// TX/RX counters are on AXI side
SIPIfcCounters #(.N(2*`NUM_LANES), .W(64)) axiCounters (
    .clk(clk),
    .m(sipCounters[0]),
    .inc({rx_axis_tvalid & rx_axis_tready, tx_axis_tvalid & tx_axis_tready})
);

// RX and error counters need CDC from lane side
SIPIfc sipUserCounters_u();
SIPIfcCDC #(.MAX_BYTES(8)) userCdc (
    .mClk(clk),
    .m(sipCounters[1]),
    .sClk(user_clk),
    .s(sipUserCounters_u)
);
// Needs to be a power of 2, so pad inc with zeros
// Pipe inc signals---they're timing-critical. One stage is sufficient (and
// using more causes SRLs to be inferred).
(* shreg_extract= "no" *) reg [8*`NUM_LANES-1:0] incPipe0_u = 0;
(* shreg_extract= "no" *) reg [8*`NUM_LANES-1:0] incPipe1_u = 0;
always @(posedge user_clk) begin
    incPipe0_u <= {{`NUM_LANES{2'b0}}, ~channel_up_u & lane_enabled_u, soft_err_u, bad_seq_count_inc_u, bad_crc_count_inc_u, overflow_count_inc_u, rx_lane_tvalid_u & lane_enabled_u};
    incPipe1_u <= incPipe0_u;
end

SIPIfcCounters #(.N(8*`NUM_LANES), .W(64)) userCounters (
    .clk(user_clk),
    .m(sipUserCounters_u),
    .inc(incPipe1_u)
);

