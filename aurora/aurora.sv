// Combines two quads and a control interface
module aurora_impl (
    input           ap_clk,
    // Note no reset; reset is internally controlled by the control core
    
    // AXI-Stream ports
    `AURORA_AXIS_DEF(0)
    `AURORA_AXIS_DEF(1)
    `AURORA_AXIS_DEF(2)
    `AURORA_AXIS_DEF(3)
    `AURORA_AXIS_DEF(4)
    `AURORA_AXIS_DEF(5)
    `AURORA_AXIS_DEF(6)
    `AURORA_AXIS_DEF(7)

    // AXI4-Lite slave interface
    input           s_axi_control_awvalid,
    output          s_axi_control_awready,
    input  [15:0]   s_axi_control_awaddr ,
    input           s_axi_control_wvalid ,
    output          s_axi_control_wready ,
    input  [31:0]   s_axi_control_wdata  ,
    input  [3:0]    s_axi_control_wstrb  ,
    input           s_axi_control_arvalid,
    output          s_axi_control_arready,
    input  [15:0]   s_axi_control_araddr ,
    output          s_axi_control_rvalid ,
    input           s_axi_control_rready ,
    output [31:0]   s_axi_control_rdata  ,
    output [1:0]    s_axi_control_rresp  ,
    output          s_axi_control_bvalid ,
    input           s_axi_control_bready ,
    output [1:0]    s_axi_control_bresp  , 

    // Transceiver signals -- quad 0
    input           gt0_refclk_p,
    input           gt0_refclk_n,
    input  [3:0]    gt0_rxp_in,
    input  [3:0]    gt0_rxn_in,
    output [3:0]    gt0_txp_out,
    output [3:0]    gt0_txn_out,
    
    // Transceiver signals -- quad 1
    input           gt1_refclk_p,
    input           gt1_refclk_n,
    input  [3:0]    gt1_rxp_in,
    input  [3:0]    gt1_rxn_in,
    output [3:0]    gt1_txp_out,
    output [3:0]    gt1_txn_out,

    // Init clock, used for the reset sequence; 
    input           init_clk
);

// Assign external flat AXIS interfaces to vectors
wire [`NUM_LANES*2-1:0][`AURORA_AXIS_WIDTH-1:0]    tx_axis_tdata;
wire [`NUM_LANES*2-1:0]                           tx_axis_tvalid;
wire [`NUM_LANES*2-1:0]                           tx_axis_tready;
wire [`NUM_LANES*2-1:0][`AURORA_AXIS_WIDTH-1:0]    rx_axis_tdata;
wire [`NUM_LANES*2-1:0]                           rx_axis_tvalid;
wire [`NUM_LANES*2-1:0]                           rx_axis_tready;

`AURORA_AXIS_TO_VEC(0)
`AURORA_AXIS_TO_VEC(1)
`AURORA_AXIS_TO_VEC(2)
`AURORA_AXIS_TO_VEC(3)
`AURORA_AXIS_TO_VEC(4)
`AURORA_AXIS_TO_VEC(5)
`AURORA_AXIS_TO_VEC(6)
`AURORA_AXIS_TO_VEC(7)

// Quad reset signal (in ap_clk domain)
wire  quad_rstn;

// Generate Aurora reset signals
wire  init_rstn;
wire  init_rstn_i;
xpm_cdc_async_rst reset_sync_i (
    .src_arst   (init_rstn),
    .dest_clk   (init_clk),
    .dest_arst  (init_rstn_i)
);

reg reset_pb_i;
reg pma_init_i;

// use rst_cnt to generate asserted reset_pb longer than 1 second.
// init_clk is 100MHz, so 27-bit counter is needed. 
reg [26:0]      rst_cnt;
always @ (posedge init_clk) begin
    if (!init_rstn_i) begin
        reset_pb_i <= 1'b1;
        pma_init_i <= 1'b1;
        rst_cnt    <= 27'b0;
    end else begin
        if (rst_cnt != 27'h7ff_ffff) begin
            rst_cnt <= rst_cnt + 1'b1;
        end
        if (rst_cnt == 27'h7ff_ff00) begin
            pma_init_i <= 1'b0;
        end
        if (rst_cnt == 27'h7ff_ffff) begin
            reset_pb_i <= 1'b0;
        end
    end
end

