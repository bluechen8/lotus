// These defines are similar to those in lotus/top/global_defines.vh.in, but there
// are differences (e.g., tx and rx directions are flipped, there are only
// 3 ports per aurora kernel, etc.)
// NOTE: Keep this in sync with CROSS_DEVICE_AXIS_WIDTH, and keep it in sync
// with the width of the Verilog wrapper (in aurora.v!)
`define AURORA_AXIS_WIDTH (96)

`define AURORA_AXIS_DEF(id) \
    input                            tx``id``_axis_tvalid, \
    input  [`AURORA_AXIS_WIDTH-1:0]  tx``id``_axis_tdata, \
    output                           tx``id``_axis_tready, \
    output                           rx``id``_axis_tvalid, \
    output [`AURORA_AXIS_WIDTH-1:0]  rx``id``_axis_tdata, \
    input                            rx``id``_axis_tready, \

`define AURORA_AXIS_TO_VEC(id) \
    assign tx_axis_tvalid[``id``] = tx``id``_axis_tvalid; \
    assign tx_axis_tdata[``id``] = tx``id``_axis_tdata; \
    assign tx``id``_axis_tready = tx_axis_tready[``id``]; \
    assign rx``id``_axis_tvalid = rx_axis_tvalid[``id``]; \
    assign rx``id``_axis_tdata = rx_axis_tdata[``id``]; \
    assign rx_axis_tready[``id``] = rx``id``_axis_tready; \

`define AURORA_MODNAME(id) aurora_64b66b_``id`` 

// Lanes per quad
`define NUM_LANES 4

// A quad encapsulates all the lanes in a QSFP interface, and its conversion
// from/to AXI-Stream ports
module aurora_quad #(
    parameter QUAD_ID = 0
) (
    input clk,
    input rstn, // affects logic between Aurora and AXIS I/O. Aurora itself is initialized on init_clk

    // External interfaces (on clk domain)
    input  [`NUM_LANES-1:0][`AURORA_AXIS_WIDTH-1:0]    tx_axis_tdata,
    input  [`NUM_LANES-1:0]                            tx_axis_tvalid,
    output [`NUM_LANES-1:0]                            tx_axis_tready,
    output [`NUM_LANES-1:0][`AURORA_AXIS_WIDTH-1:0]    rx_axis_tdata,
    output [`NUM_LANES-1:0]                            rx_axis_tvalid,
    input  [`NUM_LANES-1:0]                            rx_axis_tready,

    input  [`NUM_LANES-1:0]    lane_enabled, // from control core
    
    // Transceiver/Aurora initialization (all on init_clk domain)
    input init_clk,
    input reset_pb_i,
    input pma_init_i,

    // Transceiver signals
    input                      gt_refclk_p,
    input                      gt_refclk_n,
    input  [`NUM_LANES-1:0]    gt_rxp_in,
    input  [`NUM_LANES-1:0]    gt_rxn_in,
    output [`NUM_LANES-1:0]    gt_txp_out,
    output [`NUM_LANES-1:0]    gt_txn_out,

    // Status and counters
    output [28:0] aurora_status,
    SIPIfc.master sip // only counters for now; could add aurora_status as well
);

// Internal clocks and resets
// All Aurora modules run at user_clk, type. ~400MHz. This is generated by the
// Aurora master lane. ALL SIGNALS ON THIS CLOCK MUST END IN _u
wire user_clk; 
wire rstn_u;  // with user_clk
xpm_cdc_sync_rst reset_sync_u (
    .src_rst  (rstn),
    .dest_clk (user_clk),
    .dest_rst (rstn_u)
);

/***************************
 * PART 1: TX/RX datapaths *
 ***************************/

// Lane enables
wire [`NUM_LANES-1:0]    lane_enabled_u;
xpm_cdc_array_single #(.WIDTH(`NUM_LANES)) lane_enabled_sync_u (
    .src_in     (lane_enabled),
    .src_clk    (clk),
    .dest_clk   (user_clk),
    .dest_out   (lane_enabled_u)
);

// Clock-domain crossing FIFOs
wire [`NUM_LANES-1:0][`AURORA_AXIS_WIDTH-1:0]    tx_axis_tdata_u;
wire [`NUM_LANES-1:0]                           tx_axis_tvalid_u;
wire [`NUM_LANES-1:0]                           tx_axis_tready_u;
wire [`NUM_LANES-1:0][`AURORA_AXIS_WIDTH-1:0]    rx_axis_tdata_u;
wire [`NUM_LANES-1:0]                           rx_axis_tvalid_u;
wire [`NUM_LANES-1:0]                           rx_axis_tready_u;

for (genvar i = 0; i < `NUM_LANES ; i = i + 1) begin : cdc_fifos
    axis_data_fifo_s tx_fifo_s_to_u (
        .s_axis_aresetn   (rstn),
        .s_axis_aclk      (clk),
        .s_axis_tvalid    (tx_axis_tvalid[i]),
        .s_axis_tready    (tx_axis_tready[i]),
        .s_axis_tdata     (tx_axis_tdata[i]),
        .m_axis_aclk      (user_clk),
        .m_axis_tvalid    (tx_axis_tvalid_u[i]),
        .m_axis_tready    (tx_axis_tready_u[i]),
        .m_axis_tdata     (tx_axis_tdata_u[i])
    );
    axis_data_fifo_s rx_fifo_u_to_s (
        .s_axis_aresetn   (rstn_u),
        .s_axis_aclk      (user_clk),
        .s_axis_tvalid    (rx_axis_tvalid_u[i]),
        .s_axis_tready    (rx_axis_tready_u[i]),
        .s_axis_tdata     (rx_axis_tdata_u[i]),
        .m_axis_aclk      (clk),
        .m_axis_tvalid    (rx_axis_tvalid[i]),
        .m_axis_tready    (rx_axis_tready[i]),
        .m_axis_tdata     (rx_axis_tdata[i])
    );
end

// Data width conversions (axis <-> flit)
wire [`NUM_LANES-1:0][64-1:0]    tx_flit_tdata_u;
wire [`NUM_LANES-1:0]            tx_flit_tvalid_u;
wire [`NUM_LANES-1:0]            tx_flit_tready_u;
wire [`NUM_LANES-1:0][64-1:0]    rx_flit_tdata_u;
wire [`NUM_LANES-1:0]            rx_flit_tvalid_u;
wire [`NUM_LANES-1:0]            rx_flit_tready_u;

wire [`NUM_LANES-1:0][32-1:0]    rx_trailer_data_u;

for (genvar i = 0; i < `NUM_LANES ; i = i + 1) begin : width_conversion
    axis_dwidth_narrower tx_axis_to_flit (
        .aclk(user_clk),
        .aresetn(rstn_u),
        .s_axis_tvalid(tx_axis_tvalid_u[i]),
        .s_axis_tready(tx_axis_tready_u[i]),
        .s_axis_tdata({32'b0, tx_axis_tdata_u[i]}),
        .m_axis_tvalid(tx_flit_tvalid_u[i]),
        .m_axis_tready(tx_flit_tready_u[i]),
        .m_axis_tdata(tx_flit_tdata_u[i])
    );

    axis_dwidth_widener rx_flit_to_axis (
        .aclk(user_clk),
        .aresetn(rstn_u),
        .s_axis_tvalid(rx_flit_tvalid_u[i]),
        .s_axis_tready(rx_flit_tready_u[i]),
        .s_axis_tdata(rx_flit_tdata_u[i]),
        .m_axis_tvalid(rx_axis_tvalid_u[i]),
        .m_axis_tready(rx_axis_tready_u[i]),
        .m_axis_tdata({rx_trailer_data_u[i], rx_axis_tdata_u[i]})
    );
end


// Flit/flow-control FIFOs (flit <-> lane)
wire [`NUM_LANES-1:0][64-1:0]    tx_lane_tdata_u;
wire [`NUM_LANES-1:0]            tx_lane_tlast_u;
wire [`NUM_LANES-1:0]            tx_lane_tvalid_u;
wire [`NUM_LANES-1:0]            tx_lane_tready_u;
wire [`NUM_LANES-1:0][64-1:0]    rx_lane_tdata_u;
wire [`NUM_LANES-1:0]            rx_lane_tlast_u;
wire [`NUM_LANES-1:0]            rx_lane_tvalid_u;
wire [`NUM_LANES-1:0]            rx_lane_tready_u;

wire [`NUM_LANES-1:0]            overflow_count_inc_u;
wire [`NUM_LANES-1:0]            bad_crc_count_inc_u;
wire [`NUM_LANES-1:0]            bad_seq_count_inc_u;

for (genvar i = 0; i < `NUM_LANES ; i = i + 1) begin : lane_fc
    retransmit rtx_fc (
        .clk(user_clk),
        .rstn(rstn_u),
        .tx_in_tdata(tx_flit_tdata_u[i]),
        .tx_in_tvalid(tx_flit_tvalid_u[i]),
        .tx_in_tready(tx_flit_tready_u[i]),
        .rx_out_tdata(rx_flit_tdata_u[i]),
        .rx_out_tvalid(rx_flit_tvalid_u[i]),
        .rx_out_tready(rx_flit_tready_u[i]),

        .tx_out_tdata(tx_lane_tdata_u[i]),
        .tx_out_tlast(tx_lane_tlast_u[i]),
        .tx_out_tvalid(tx_lane_tvalid_u[i]),
        .tx_out_tready(tx_lane_tready_u[i]),
        .rx_in_tdata(rx_lane_tdata_u[i]),
        .rx_in_tlast(rx_lane_tlast_u[i]),
        .rx_in_tvalid(rx_lane_tvalid_u[i] && lane_enabled_u[i]),
        .rx_in_tready(rx_lane_tready_u[i]), // not used, lane keeps blowing packets through
        
        .overflow_count_inc(overflow_count_inc_u[i]),
        .bad_crc_count_inc(bad_crc_count_inc_u[i]),
        .bad_seq_count_inc(bad_seq_count_inc_u[i])
    );
end


